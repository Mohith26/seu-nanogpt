"""Turn results/*.jsonl into the tables in results/summary.md (no torch needed)."""
import collections
import json
import os
import statistics

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")


def outcome(r):
    if r["nonfinite"] or r["val"] is None:
        return "diverged"
    d = r["val"] - r["clean_val"]
    if d > 0.5:
        return "diverged"
    if abs(d) < 0.005:
        return "masked"
    return "degraded" if d > 0 else "improved"


def single_fault():
    rs = [json.loads(line) for line in open(os.path.join(RES, "single_fault.jsonl"))]
    lines = ["## Experiment 1: one bit flip at step 1000, measured 200 steps later", "",
             f"{len(rs)} trials (3 targets x 32 bit positions x 4 random elements). Clean continuation val loss: {rs[0]['clean_val']:.4f}.", "",
             "| target | bit class | trials | masked | degraded | diverged |", "|---|---|---|---|---|---|"]
    tab = collections.defaultdict(collections.Counter)
    for r in rs:
        tab[(r["target"], r["bit_class"])][outcome(r)] += 1
    for t in ["param", "exp_avg", "exp_avg_sq"]:
        for c in ["mantissa", "exponent", "sign"]:
            v = tab[(t, c)]
            lines.append(f"| {t} | {c} | {sum(v.values())} | {v['masked']} | {v['degraded']} | {v['diverged']} |")
    lines += ["", "Every non-masked trial, by bit position:", "", "| target | bit | value before -> after | val loss change | non-finite |", "|---|---|---|---|---|"]
    for r in rs:
        if outcome(r) != "masked":
            d = "n/a" if r["val"] is None else f"{r['val'] - r['clean_val']:+.3f}"
            lines.append(f"| {r['target']} | {r['bit']} | {r['old']:.3g} -> {r['new']:.3g} | {d} | {r['nonfinite']} |")
    bad = collections.Counter((r["target"], r["bit"]) for r in rs if outcome(r) != "masked")
    lines += ["", f"Bad (target, bit) combinations: {sorted(bad)}; that is {len(bad)} of 96, so about {100 * len(bad) / 96:.1f}% of uniformly random upsets in this state."]
    return lines


def guard():
    rs = [json.loads(line) for line in open(os.path.join(RES, "guard.jsonl"))]
    by = {(r["seed"], r["mode"]): r for r in rs}
    seeds = sorted({r["seed"] for r in rs})
    lines = ["## Experiment 2: 2000-step training runs, ~1 upset per 25 steps", "",
             "| seed | upsets | clean val | faults: val | faults+guard: val | guard rollbacks | replayed steps |", "|---|---|---|---|---|---|---|"]

    def fmt(r):
        if r["val"] is None:
            return f"NaN (diverged at step {r['diverged_at']})"
        return f"{r['val']:.4f}"
    for s in seeds:
        c, f, g = by[(s, "clean")], by[(s, "faults")], by[(s, "faults+guard")]
        lines.append(f"| {s} | {f['upsets']} | {c['val']:.4f} | {fmt(f)} | {fmt(g)} | {g['rollbacks']} | {g['replayed_steps']} |")
    cg = [by[(s, "clean+guard")] for s in seeds]
    false_trips = sum(r["rollbacks"] for r in cg)
    same = sum(1 for s in seeds if by[(s, "clean+guard")]["val"] == by[(s, "clean")]["val"])
    ms_c = statistics.median(by[(s, "clean")]["ms_per_executed_step"] for s in seeds)
    ms_g = statistics.median(by[(s, "clean+guard")]["ms_per_executed_step"] for s in seeds)
    unguarded_nan = sum(1 for s in seeds if by[(s, "faults")]["val"] is None)
    guarded_gap = [by[(s, "faults+guard")]["val"] - by[(s, "clean")]["val"] for s in seeds]
    lines += ["",
              f"- Unguarded: {unguarded_nan}/{len(seeds)} runs ended in NaN; the rest finished with val loss change "
              + ", ".join(f"{by[(s, 'faults')]['val'] - by[(s, 'clean')]['val']:+.3f}" for s in seeds if by[(s, 'faults')]['val'] is not None) + ".",
              f"- Guarded: {len(seeds)}/{len(seeds)} runs finished; val loss change vs clean: " + ", ".join(f"{d:+.3f}" for d in guarded_gap) + ".",
              f"- False alarms on fault-free runs with the guard on: {false_trips} rollbacks; {same}/{len(seeds)} guarded clean runs reproduced the clean val loss exactly.",
              f"- Median time per step on fault-free runs: {ms_c:.2f} ms without the guard, {ms_g:.2f} ms with it ({100 * (ms_g / ms_c - 1):+.1f}%; Apple Silicon CPU, 4 threads, noisy at this size)."]
    return lines


if __name__ == "__main__":
    out = ["# Results", "", "Generated by experiments/summarize.py from the JSONL files in this folder.", ""] + single_fault() + [""] + guard() + [""]
    with open(os.path.join(RES, "summary.md"), "w") as f:
        f.write("\n".join(out))
    print("\n".join(out))
